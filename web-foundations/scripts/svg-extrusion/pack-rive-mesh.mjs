#!/usr/bin/env node
// Packs a generated svg-to-rive-3d provider (geometry.json + manifest.json)
// into the Rive project's blob assets and a generated AnimaScript constants
// module. Deterministic: same inputs produce byte-identical outputs.
//
// Usage: node pack-rive-mesh.mjs <geometry.json> <manifest.json> <out-dir>
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const [geometryPath, manifestPath, outDir] = process.argv.slice(2);
if (!geometryPath || !manifestPath || !outDir) {
	console.error('usage: pack-rive-mesh.mjs <geometry.json> <manifest.json> <out-dir>');
	process.exit(2);
}

const geometry = JSON.parse(readFileSync(geometryPath, 'utf8'));
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));

if (geometry.schema !== 'rive-animascript-3d/generated-provider/v1') {
	throw new Error(`unexpected geometry schema: ${geometry.schema}`);
}
if (manifest.schema !== 'svg-to-rive-3d/v1') {
	throw new Error(`unexpected manifest schema: ${manifest.schema}`);
}

const positions = geometry.positions;
const normals = geometry.normals;
const indices = geometry.indices;
const vertexCount = positions.length / 3;
const indexCount = indices.length;
if (!Number.isInteger(vertexCount) || vertexCount <= 0) throw new Error('bad vertex count');
if (normals.length !== positions.length) throw new Error('normals/positions length mismatch');
if (indexCount === 0 || indexCount % 3 !== 0) throw new Error('bad index count');
if (vertexCount > 65536) throw new Error('uint16 index buffer cannot address this mesh');

const facets = manifest.facets;
if (!Array.isArray(facets) || facets.length === 0) throw new Error('manifest has no facets');
if (manifest.facetCount !== facets.length) throw new Error('facetCount mismatch');

// Per-vertex source fill and facet id, resolved through each facet's declared
// vertex span. facetId is the manifest source-order index (0-based) and rides
// in the vertex record so the CPU picker never guesses identity.
const vertexFill = new Array(vertexCount).fill(null);
const vertexFacet = new Array(vertexCount).fill(-1);
let cursor = 0;
for (let facetIndex = 0; facetIndex < facets.length; facetIndex++) {
	const facet = facets[facetIndex];
	const span = facet.mesh;
	if (!span || span.vertexStart !== cursor) {
		throw new Error(`${facet.id}: vertex spans must be contiguous from 0`);
	}
	if (!/^#[0-9A-Fa-f]{6}$/.test(facet.fill)) throw new Error(`${facet.id}: bad fill ${facet.fill}`);
	for (let v = span.vertexStart; v < span.vertexStart + span.vertexCount; v++) {
		if (v >= vertexCount) throw new Error(`${facet.id}: vertex span out of range`);
		vertexFill[v] = facet.fill;
		vertexFacet[v] = facetIndex;
	}
	cursor += span.vertexCount;
}
if (cursor !== vertexCount) throw new Error('facet vertex spans do not cover the mesh');
for (const index of indices) {
	if (!Number.isInteger(index) || index < 0 || index >= vertexCount) {
		throw new Error(`index out of range: ${index}`);
	}
}
if (vertexFacet.some((f) => f < 0)) throw new Error('uncovered vertex has no facet');

const VERTEX_STRIDE = 40; // vec3 position + vec3 normal + vec3 colour + f32 facetId
const vertices = Buffer.alloc(vertexCount * VERTEX_STRIDE);
for (let v = 0; v < vertexCount; v++) {
	const o = v * VERTEX_STRIDE;
	for (let c = 0; c < 3; c++) {
		vertices.writeFloatLE(positions[v * 3 + c], o + c * 4);
		vertices.writeFloatLE(normals[v * 3 + c], o + 12 + c * 4);
		const hex = parseInt(vertexFill[v].slice(1 + c * 2, 3 + c * 2), 16);
		vertices.writeFloatLE(hex / 255, o + 24 + c * 4);
	}
	vertices.writeFloatLE(vertexFacet[v], o + 36);
}

const indexBuffer = Buffer.alloc(indexCount * 2);
for (let i = 0; i < indexCount; i++) indexBuffer.writeUInt16LE(indices[i], i * 2);

const xs = positions.filter((_, i) => i % 3 === 0);
const ys = positions.filter((_, i) => i % 3 === 1);
const zs = positions.filter((_, i) => i % 3 === 2);
const bounds = {
	minX: Math.min(...xs),
	maxX: Math.max(...xs),
	minY: Math.min(...ys),
	maxY: Math.max(...ys),
	minZ: Math.min(...zs),
	maxZ: Math.max(...zs),
};

const f = (n) => {
	const v = Math.fround(n);
	return Object.is(v, -0) ? '0' : String(v);
};
const as = `// Generated by pack-rive-mesh.mjs from geometry.json + manifest.json.
// Do not edit; regenerate through the packer.
export const VERTEX_COUNT: u32 = ${vertexCount};
export const INDEX_COUNT: u32 = ${indexCount};
export const FACET_COUNT: u32 = ${facets.length};
export const BOUNDS_MIN_X: f32 = ${f(bounds.minX)};
export const BOUNDS_MAX_X: f32 = ${f(bounds.maxX)};
export const BOUNDS_MIN_Y: f32 = ${f(bounds.minY)};
export const BOUNDS_MAX_Y: f32 = ${f(bounds.maxY)};
export const BOUNDS_MIN_Z: f32 = ${f(bounds.minZ)};
export const BOUNDS_MAX_Z: f32 = ${f(bounds.maxZ)};
`;

writeFileSync(resolve(outDir, 'favicon-vertices.bin'), vertices);
writeFileSync(resolve(outDir, 'favicon-indices.bin'), indexBuffer);
writeFileSync(resolve(outDir, 'favicon_mesh.as'), as);
console.log(`packed ${vertexCount} vertices, ${indexCount} indices, ${facets.length} facets -> ${outDir}`);
